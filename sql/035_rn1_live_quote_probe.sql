-- Causal live CLOB order-book sampling for RN1 strategy research.
-- Observations are recorded BEFORE later wallet fills; never reconstruct
-- historical books from current snapshots. Archive full books privately.
create table if not exists pi.rn1_quote_probe_state(
  singleton boolean primary key default true check(singleton),
  status text not null default 'collecting'
    check(status in('collecting','paused_quota','paused_error')),
  lease_until timestamptz,
  completed_runs bigint not null default 0,
  matched_fills bigint not null default 0,
  archived_gzip_bytes bigint not null default 0,
  last_success_at timestamptz,
  last_error text,
  error_streak integer not null default 0,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  max_db_bytes bigint not null default 304087040,
  max_archive_bytes bigint not null default 734003200,
  check(max_db_bytes between 209715200 and 536870912),
  check(max_archive_bytes between 52428800 and 1073741824)
);
insert into pi.rn1_quote_probe_state(singleton) values (true)
on conflict(singleton) do nothing;

create table if not exists pi.rn1_quote_probe_runs(
 id bigint generated by default as identity primary key,
 slot_at timestamptz not null unique,
 requested_at timestamptz not null,
 received_at timestamptz not null,
 source text not null default 'clob_public_rest_books',
 market_count integer not null check(market_count between 1 and 8),
 book_count integer not null check(book_count between 1 and 16),
 rn1_market_count integer not null default 0,
 archive_key text not null unique,
 raw_sha256 text not null check(raw_sha256 ~ '^[0-9a-f]{64}$'),
 compressed_bytes integer not null check(compressed_bytes between 1 and 20000000),
 quotes jsonb not null check(jsonb_typeof(quotes)='array'),
 created_at timestamptz not null default now(),
 check(received_at>=requested_at)
);
create index if not exists idx_rn1_quote_runs_received
 on pi.rn1_quote_probe_runs(received_at desc);

create table if not exists pi.rn1_quote_probe_fills(
 fingerprint text primary key check(fingerprint ~ '^[0-9a-f]{64}$'),
 run_id bigint not null references pi.rn1_quote_probe_runs(id),
 market_key text not null,
 token_id text not null,
 trade_at timestamptz not null,
 side text not null check(side in('BUY','SELL')),
 role text not null check(role in('maker_inferred','taker_verified','unknown')),
 fill_price numeric not null check(fill_price between 0 and 1),
 shares numeric not null check(shares>0),
 lag_seconds numeric not null check(lag_seconds>=10 and lag_seconds<=120),
 pre_bid numeric not null check(pre_bid between 0 and 1),
 pre_ask numeric not null check(pre_ask between 0 and 1),
 pre_mid numeric not null check(pre_mid between 0 and 1),
 pre_spread numeric not null check(pre_spread>=0),
 bid_offset_ticks numeric not null,
 book_timestamp timestamptz,
 source_group text not null check(source_group in('rn1_recent','sports_control')),
 sports_taker_fee_estimate numeric,
 matched_at timestamptz not null default now()
);
create index if not exists idx_rn1_quote_probe_fill_time on pi.rn1_quote_probe_fills(trade_at desc);
create index if not exists idx_rn1_quote_probe_fill_market on pi.rn1_quote_probe_fills(market_key,trade_at desc);

alter table pi.rn1_quote_probe_state enable row level security;
alter table pi.rn1_quote_probe_runs enable row level security;
alter table pi.rn1_quote_probe_fills enable row level security;
revoke all on pi.rn1_quote_probe_state,pi.rn1_quote_probe_runs,pi.rn1_quote_probe_fills
 from public,anon,authenticated;
grant select,insert,update,delete on
 pi.rn1_quote_probe_state,pi.rn1_quote_probe_runs,pi.rn1_quote_probe_fills to service_role;
grant usage,select on all sequences in schema pi to service_role;
comment on table pi.rn1_quote_probe_runs is
 'Full order books stored as private gzip; sampled bid/ask quotes represent pre-fill evidence only when the quote response preceded a later observed trade.';
comment on table pi.rn1_quote_probe_fills is
 'Only fills matched to a previously observed book, 10-120 seconds earlier. No claim that sampled levels were RN1 unexecuted orders.';
